    public_id          varchar(32) NOT NULL,
    user_id            bigint NOT NULL REFERENCES public.account_users(id),
    amount_cents       bigint NOT NULL,
    channel            varchar(16) NOT NULL,
    account            varchar(128) NOT NULL,
    real_name          varchar(64) NOT NULL,
    status             varchar(16) NOT NULL,
    reference          varchar(128),
    reject_reason      varchar(200),
    requested_at       timestamptz NOT NULL DEFAULT clock_timestamp(),
    decided_at         timestamptz,
    decided_by_user_id bigint REFERENCES public.account_users(id),
    CONSTRAINT agent_withdrawals_public_id_uidx UNIQUE (public_id),
    CONSTRAINT agent_withdrawals_amount_pos CHECK (amount_cents > 0),
    CONSTRAINT agent_withdrawals_channel_known CHECK (channel IN ('alipay', 'wechat')),
    CONSTRAINT agent_withdrawals_status_known
        CHECK (status IN ('pending', 'paid', 'rejected')),
    CONSTRAINT agent_withdrawals_terminal_shape CHECK (
        (status = 'pending' AND decided_at IS NULL AND decided_by_user_id IS NULL
            AND reference IS NULL AND reject_reason IS NULL)
        OR (status = 'paid' AND decided_at IS NOT NULL AND decided_by_user_id IS NOT NULL
            AND reject_reason IS NULL)
        OR (status = 'rejected' AND decided_at IS NOT NULL AND decided_by_user_id IS NOT NULL
            AND reject_reason IS NOT NULL AND btrim(reject_reason) <> ''))
);

