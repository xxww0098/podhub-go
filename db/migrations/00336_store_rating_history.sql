-- Post-Rust append. A row is inserted only when status or current_value
-- changes. The prune job deletes rows older than the retention window.
-- +goose StatementBegin
CREATE TABLE public.store_rating_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id bigint NOT NULL REFERENCES public.organizations (id) ON DELETE CASCADE,
    store_id uuid NOT NULL REFERENCES public.organization_stores (uuid) ON DELETE CASCADE,
    rating_key text NOT NULL,
    name text NOT NULL DEFAULT '',
    value_type text NOT NULL DEFAULT '',
    status text NOT NULL DEFAULT '',
    current_value numeric,
    past_value numeric,
    recorded_at timestamptz NOT NULL,
    CONSTRAINT store_rating_history_org CHECK (org_id > 0),
    CONSTRAINT store_rating_history_key_len CHECK (char_length(rating_key) BETWEEN 1 AND 128),
    CONSTRAINT store_rating_history_text_len CHECK (
        char_length(name) <= 400
        AND char_length(value_type) <= 64
        AND char_length(status) <= 64
    ),
    CONSTRAINT store_rating_history_clean CHECK (
        rating_key !~* '(fixture-api-key|api[-_]?key|bearer |sk-|client[-_]?id|signature=|x-amz-)'
        AND name !~* '(fixture-api-key|api[-_]?key|bearer |sk-|client[-_]?id|signature=|x-amz-)'
        AND value_type !~* '(fixture-api-key|api[-_]?key|bearer |sk-|client[-_]?id|signature=|x-amz-)'
        AND status !~* '(fixture-api-key|api[-_]?key|bearer |sk-|client[-_]?id|signature=|x-amz-)'
    )
);

CREATE INDEX store_rating_history_key_idx
    ON public.store_rating_history (org_id, store_id, rating_key, id DESC);
CREATE INDEX store_rating_history_recorded_idx
    ON public.store_rating_history (recorded_at);

REVOKE ALL ON TABLE public.store_rating_history FROM PUBLIC;
REVOKE ALL ON SEQUENCE public.store_rating_history_id_seq FROM PUBLIC;
GRANT SELECT, INSERT, DELETE ON TABLE public.store_rating_history TO podhub_app, podhub_worker;
GRANT USAGE, SELECT ON SEQUENCE public.store_rating_history_id_seq TO podhub_app, podhub_worker;

ALTER TABLE public.store_rating_history ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.store_rating_history FORCE ROW LEVEL SECURITY;

