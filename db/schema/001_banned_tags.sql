CREATE TABLE public.banned_tags (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    term text NOT NULL,
    match_mode text NOT NULL,
    note text NOT NULL DEFAULT '',
    created_by text NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT clock_timestamp(),
    enabled boolean NOT NULL DEFAULT true,
    CONSTRAINT banned_tags_term_key UNIQUE (term),
    CONSTRAINT banned_tags_term_nonempty CHECK (length(btrim(term)) > 0),
    CONSTRAINT banned_tags_match_mode CHECK (match_mode IN ('exact', 'stem'))
);
