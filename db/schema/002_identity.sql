-- sqlc schema for the identity and tenant queries.
-- Runtime schema is the goose chain. This file only has to name the columns
-- those queries touch.

CREATE TABLE public.plans (
    key character varying(32) PRIMARY KEY,
    active boolean NOT NULL
);

CREATE TABLE public.account_users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id character varying(64) NOT NULL,
    email character varying(320) NOT NULL,
    password_hash character varying(255) NOT NULL,
    role character varying(32) NOT NULL,
    name character varying(255) NOT NULL,
    target character varying(64) NOT NULL,
    supplier_id character varying(64) NOT NULL,
    plan character varying(32) NOT NULL,
    disabled_at timestamp with time zone,
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    active_org_id bigint,
    last_login_at timestamp with time zone,
    email_verified_at timestamp with time zone,
    invited_by_agent_user_id bigint,
    agent_attributed_at timestamp with time zone,
    agent_attribution_bps integer,
    agent_attribution_source character varying(16),
    CONSTRAINT uq_account_users_email UNIQUE (email)
);

CREATE TABLE public.account_credentials (
    user_id bigint PRIMARY KEY,
    password_hash character varying(255) NOT NULL,
    updated_at timestamp with time zone NOT NULL
);

CREATE TABLE public.account_profiles (
    user_id bigint PRIMARY KEY,
    name character varying(255) NOT NULL,
    target character varying(64) NOT NULL,
    supplier_id character varying(64) NOT NULL,
    active_org_id bigint,
    updated_at timestamp with time zone NOT NULL,
    avatar_bytes bytea,
    avatar_updated_at_ms bigint,
    name_changed_at_ms bigint
);

CREATE TABLE public.account_sessions (
    token_hash character varying(128) PRIMARY KEY,
    user_id bigint NOT NULL,
    expires_at timestamp with time zone NOT NULL,
    admin_step_up_until timestamp with time zone
);

CREATE TABLE public.account_admin_totp (
    user_id bigint PRIMARY KEY,
    confirmed_at timestamp with time zone
);

CREATE TABLE public.organizations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id bigint NOT NULL,
    name character varying(255) NOT NULL,
    plan character varying(32) NOT NULL,
    seat_limit bigint NOT NULL,
    psd_upload_enabled boolean NOT NULL,
    uuid uuid NOT NULL,
    dissolved_at timestamp with time zone,
    avatar_bytes bytea,
    avatar_updated_at_ms bigint,
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL
);

CREATE TABLE public.organization_members (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id bigint NOT NULL,
    user_id bigint NOT NULL,
    role character varying(32) NOT NULL,
    status character varying(32) NOT NULL,
    display_name character varying(255) NOT NULL,
    join_order bigint NOT NULL,
    manual_disabled boolean NOT NULL,
    quota_suspended boolean NOT NULL,
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    CONSTRAINT uq_org_members_org_user UNIQUE (org_id, user_id)
);

CREATE TABLE public.org_invitations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id bigint NOT NULL,
    email character varying(320) NOT NULL,
    accepted_at timestamp with time zone,
    revoked_at timestamp with time zone,
    declined_at timestamp with time zone,
    expires_at timestamp with time zone NOT NULL,
    invitee_user_id bigint,
    updated_at timestamp with time zone NOT NULL
);

CREATE TABLE public.audit_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id bigint NOT NULL,
    user_id bigint NOT NULL,
    module character varying(64) NOT NULL,
    entity_type character varying(64) NOT NULL,
    entity_id character varying(128) NOT NULL,
    api_method character varying(16) NOT NULL,
    api_path character varying(512) NOT NULL,
    action character varying(64) NOT NULL,
    status character varying(64) NOT NULL,
    result character varying(64) NOT NULL,
    message text NOT NULL,
    shop_id bigint,
    created_at_ms bigint NOT NULL,
    created_at timestamp with time zone NOT NULL,
    actor_kind character varying(16) NOT NULL,
    support_grant_id bigint,
    writer_lease_id bigint,
    writer_fence_token bigint
);

CREATE TABLE public.auth_login_attempts (
    email_hash bytea NOT NULL,
    ip_hash bytea NOT NULL,
    failures integer NOT NULL,
    window_start timestamp with time zone NOT NULL,
    next_allowed_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    PRIMARY KEY (email_hash, ip_hash)
);

CREATE TABLE public.auth_email_tokens (
    token_hash text PRIMARY KEY,
    user_id bigint NOT NULL,
    purpose text NOT NULL,
    expires_at timestamp with time zone NOT NULL,
    consumed_at timestamp with time zone,
    created_at timestamp with time zone NOT NULL
);

CREATE TABLE public.platform_initialization (
    singleton boolean PRIMARY KEY,
    owner_account_id bigint
);

CREATE TABLE public.listing_card_cursors (
    org_id bigint NOT NULL,
    card_id uuid NOT NULL,
    seq bigint NOT NULL DEFAULT 0,
    PRIMARY KEY (org_id, card_id)
);

-- Subscription term. The identity bootstrap creates a free row per workspace.
CREATE TABLE public.subscriptions (
    org_id bigint PRIMARY KEY,
    status text NOT NULL,
    plan_key text NOT NULL,
    term_start timestamp with time zone,
    term_end timestamp with time zone,
    extra_stores integer NOT NULL,
    extra_members integer NOT NULL,
    next_plan_key text,
    next_extra_stores integer NOT NULL,
    next_extra_members integer NOT NULL,
    next_keep_store_ids uuid[] NOT NULL,
    next_keep_member_ids bigint[] NOT NULL,
    revision bigint NOT NULL,
    updated_at timestamp with time zone NOT NULL
);
