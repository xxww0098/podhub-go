#[test]
fn descriptor_base64_blobs_byte_round_trip() {
    for (index, expected) in BLOBS.iter().enumerate() {
        let mut reader = PsdReader::new(expected, None, None);
        let desc = read_descriptor_structure(&mut reader)
            .unwrap_or_else(|e| panic!("blob {index}: read: {e}"));
        let mut writer = create_writer(expected.len().max(64));
        write_descriptor_structure(&mut writer, &desc);
        let actual = writer.to_bytes();
        assert_eq!(
            actual.as_slice(),
            *expected,
            "descriptor blob {index}: byte mismatch (act {} exp {})",
            actual.len(),
            expected.len()
        );
    }
}
