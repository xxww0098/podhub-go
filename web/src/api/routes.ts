export type RouteKey = keyof typeof ROUTES

/** Values accepted for a path parameter. */
export type RouteParams = Record<string, string | number>

/**
 * Fill one route template. Values are percent-encoded; a `{*name}` wildcard is
 * substituted raw, because it stands for a path suffix rather than one segment.
 */
export function route(key: RouteKey, params?: RouteParams): string {
  const template: string = ROUTES[key]
  return template.replace(/\{(\*?)([a-z_]+)\}/g, (_match, wildcard: string, name: string) => {
    const value = params?.[name]
    if (value === undefined || value === null || value === "") {
      throw new Error("route(" + key + "): missing path parameter " + name)
    }
    return wildcard ? String(value) : encodeURIComponent(String(value))
  })
}
