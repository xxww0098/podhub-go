/**
 * The SPA's single path authority.
 *
 * Every Cloud path the browser calls is spelled once, here. `ROUTES` is pinned
 * to the generated OpenAPI view (`keyof paths`), apart from the narrow pending
 * list below, so a removed path or typo fails `tsc` instead of production;
 * renaming an endpoint is one line here plus whatever the type error names.
 *
 * Keys are mechanical: path segments in camelCase, a parameter segment becoming
 * `By<PascalName>` (`/api/listing/rows/{id}` -> `listingRowsById`). Renaming a
 * path parameter therefore renames its key, and that rename is a find-and-replace
 * confined to this file and its call sites.
 *
 * routes.test.ts forbids a raw path literal anywhere else in the SPA; the files
 * that still carry one are listed there as a ratchet that may only shrink.
 *
 * Not every generated path has a caller: the server documents routes the SPA does
 * not use (Seller upstream passthrough, payment callbacks, some admin probes).
 * They stay here so the table is exactly the documented surface.
 */
