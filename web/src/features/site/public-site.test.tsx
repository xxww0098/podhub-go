test("pricing, help and legal pages stay public", () => {
  const pricing = renderToStaticMarkup(<PublicSite page="pricing" />)
  assert.match(pricing, /围绕目录运营设计的套餐/)
  assert.match(pricing, /发布前公布价格/)
  assert.doesNotMatch(pricing, /¥15/)
  const help = renderToStaticMarkup(<PublicSite page="help" signedIn />)
  assert.match(help, />进入工作台</)
  assert.match(help, /在哪里登录/)
  assert.doesNotMatch(help, /报告问题/)
  assert.doesNotMatch(help, /docs\.qq\.com/)
  assert.match(help, /邮件支持/)
  const privacy = renderToStaticMarkup(<PublicSite page="privacy" />)
  assert.match(privacy, /隐私声明/)
  const terms = renderToStaticMarkup(<PublicSite page="terms" />)
  assert.match(terms, /使用条款/)
})

test("catalog page is public and gates prices behind login", () => {
  const anonymous = renderToStaticMarkup(<PublicSite page="catalog" />)
  // Static markup renders before the catalog fetch resolves.
  assert.match(anonymous, /商品目录/)
  assert.match(anonymous, /正在读取目录/)
  assert.match(anonymous, /平台价、建议零售价和下单履约在登录后开放/)
  assert.match(anonymous, /登录查看价格/)
  assert.doesNotMatch(anonymous, /¥\d|priceCents|platformPrice/i)

  const signedIn = renderToStaticMarkup(<PublicSite page="catalog" signedIn />)
  assert.match(signedIn, /进入工作台查看价格/)
})
