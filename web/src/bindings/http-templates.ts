import type { components } from "@/api/schema"

type Template = components["schemas"]["PsdTemplateView"]
const TRANSFER_TIMEOUT_MS = 10 * 60 * 1000

export function registerPsdTemplate(
  body: components["schemas"]["RegisterPsdTemplateRequest"],
  callerSignal?: AbortSignal,
) {
  return retryWhenBusy(
    () => request<Template>("POST", route("listingTemplates"), body, {}, 30_000, undefined, { reportOwner: "caller", callerSignal }),
    { cancelled: () => callerSignal?.aborted === true },
  )
}

/** S3 is not Cloud: no Cookie/auth events, Cloud envelope or URL-bearing diagnostics.
 * Unlike rendered images, an existing object is NOT proof of PSD integrity. */
export async function uploadPsdTemplate(template: Template, bytes: Uint8Array, callerSignal?: AbortSignal): Promise<void> {
  const upload = template.upload
  if (!upload || upload.headers?.content_type !== "application/octet-stream"
    || upload.headers.if_none_match !== "*" || !Number.isFinite(upload.expires_at_ms)
    || bytes.byteLength !== template.bytes) {
    throw refuse("workflow_template_upload_unavailable", "云端 PSD 直传授权无效，请刷新后重新绑定")
  }
  let url: URL
  try { url = new URL(upload.url) } catch {
    throw refuse("workflow_template_upload_unavailable", "云端 PSD 直传地址无效")
  }
  const localHttp = url.protocol === "http:" && ["127.0.0.1", "localhost", "[::1]"].includes(url.hostname)
  if ((!localHttp && url.protocol !== "https:") || url.username || url.password || url.hash) {
    throw refuse("workflow_template_upload_unavailable", "云端 PSD 直传地址不安全")
  }
  // Refresh before starting with an almost-expired grant; R2 expiry can be a CORS TypeError.
  if (upload.expires_at_ms <= Date.now() + 5000) throw uploadFailure(403)
  const timeout = requestDeadline(TRANSFER_TIMEOUT_MS, callerSignal)
  let response: Response | undefined
  try {
    try {
      response = await fetch(upload.url, {
        method: "PUT", mode: "cors", credentials: "omit", cache: "no-store",
        redirect: "error", referrerPolicy: "no-referrer", signal: timeout.signal,
        // Content-Length is signed but generated by the browser from this exact view.
        headers: {
          "Content-Type": upload.headers.content_type,
          "If-None-Match": upload.headers.if_none_match,
          ...psdChecksumHeader(upload.headers),
        },
        body: bytes as BodyInit,
      })
    } catch {
      // Never retain the raw fetch error: it may contain the bearer URL.
      throw uploadFailure(undefined, undefined, true)
    }
    if (response.ok || response.status === 412) return
    const unknown = response.status === 409 || response.status === 408 || response.status >= 500
    throw uploadFailure(response.status, retryAfterMs(response.headers), unknown)
  } finally {
    // Discard S3 XML without parsing/logging it, including on failure.
    if (response?.body) await response.body.cancel().catch(() => {})
    timeout.clear()
  }
}

function psdChecksumHeader(headers: object): Record<string, string> {
  const value = (headers as { checksumSha256?: unknown }).checksumSha256
  if (value == null || value === "") return {}
  if (typeof value !== "string" || !/^[A-Za-z0-9+/]{43}=$/.test(value)) {
    throw refuse("workflow_template_upload_unavailable", "云端 PSD 直传授权无效，请刷新后重新绑定")
  }
  return { "x-amz-checksum-sha256": value }
}

function uploadFailure(status?: number, delay?: number, outcomeUnknown = false): Error {
  const reason = { status, outcomeUnknown, name: status == null ? "TypeError" : undefined }
  return Object.assign(refuse(status == null ? "cloud_unavailable" : "workflow_template_upload_failed",
    uploadFailureMessage(reason)), { status, retryAfterMs: delay, outcomeUnknown })
}

export function confirmPsdTemplate(id: string, callerSignal?: AbortSignal) {
  return retryWhenBusy(
    () => request<Template>("POST", route("listingTemplatesByIdConfirm", { id }), undefined, {}, TRANSFER_TIMEOUT_MS, undefined, { reportOwner: "caller", callerSignal }),
    { cancelled: () => callerSignal?.aborted === true },
  )
}

export type PsdPartEtag = { partNumber: number; etag: string }

