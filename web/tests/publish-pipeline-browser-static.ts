/** `web/` is the Vite root; the committed artifacts live above it, so Vite serves those through `/@fs`. */
function servedPath(repoRoot: string, file: string): string {
  const root = path.join(repoRoot, "wasm", "dist")
  if (file.startsWith("wasm/dist/")) return `/@fs${realpathSync(root)}/${file.slice("wasm/dist/".length)}`
  if (!file.startsWith("web/")) throw new Error(`Fixture source outside web/ or wasm/dist/: ${file}`)
  return `/${file.slice(4)}`
}
export function pipelineNetworkPolicy(origin: string, repoRoot: string): BrowserNetworkPolicy {
  return { origin, mocks: [], staticPrefixes: viteStaticPrefixes(repoRoot, path.join(repoRoot, "web")),
    staticPaths: sourceFiles.map((file) => servedPath(repoRoot, file)) }
}
